function detect() {
  const q = new URLSearchParams(globalThis.location?.search ?? "").get("lang");
  if (q === "ko" || q === "en") return q;
  try { const s = localStorage.getItem(KEY); if (s === "ko" || s === "en") return s; } catch {}
  return /^ko\b/i.test(globalThis.navigator?.language ?? "") ? "ko" : "en";
}

export let lang = detect();
const listeners = new Set();
if (globalThis.document) document.documentElement.lang = lang;

export function setLang(l) {
  if (l !== "ko" && l !== "en" || l === lang) return;
  lang = l;
  try { localStorage.setItem(KEY, l); } catch {}
  if (globalThis.document) document.documentElement.lang = l;
  for (const fn of listeners) { try { fn(l); } catch (e) { console.warn("[i18n]", e); } }
}
export const onLang = fn => { listeners.add(fn); return () => listeners.delete(fn); };

export function t(key, vars = {}) {
  let s = STRINGS[lang][key] ?? STRINGS.en[key];
  if (s == null) { console.warn("[i18n] missing", key); return key; }
  if (typeof s !== "string") return s;
  return s.replace(/\{(\w+)\}/g, (m, k) => (vars[k] != null ? String(vars[k]) : m));
}
// "A, B and C" / "A, B, C"
t.list = names => {
  if (lang === "ko" || names.length < 2) return names.join(", ");
  return `${names.slice(0, -1).join(", ")} and ${names[names.length - 1]}`;
};
// a fresh name suggestion (rng() in [0, 1))
export function suggestName(rng = Math.random, l = lang) {
  const [a, b] = NAME_PARTS[l];
  const pick = arr => arr[Math.floor(rng() * arr.length)];
  return `${pick(a)} ${pick(b)}`;
}

